from abc import ABC, abstractmethod
from typing import Optional, Dict, Any
from pydantic import BaseModel, Field


class AgentExecutionResult(BaseModel):
    """
    Standardized result contract returned by any agent adapter execution.
    Clearly distinguishes mock vs. real executions, measured vs. estimated token usage,
    and execution errors vs. successful agent responses.
    """
    output: Optional[str] = Field(default=None, description="Generated agent response text")
    latency_ms: float = Field(..., description="Measured round-trip execution latency in milliseconds")
    token_usage: Optional[int] = Field(default=None, description="Total tokens consumed (prompt + completion)")
    prompt_tokens: Optional[int] = Field(default=None, description="Input prompt token count")
    completion_tokens: Optional[int] = Field(default=None, description="Output completion token count")
    tokens_estimated: bool = Field(default=True, description="True if token counts were deterministically estimated")
    is_mock: bool = Field(default=True, description="True if output was generated by a mock adapter")
    is_error: bool = Field(default=False, description="True if execution threw or simulated an error")
    error_message: Optional[str] = Field(default=None, description="Diagnostic error details if is_error is True")
    raw_response: Optional[Dict[str, Any]] = Field(default=None, description="Raw provider metadata or diagnostic flags")
    cost_usd: Optional[float] = Field(default=None, description="Reliably calculated inference cost in USD, or None if unavailable")
    model_name: Optional[str] = Field(default=None, description="Resolved model identifier used for inference")
    model_provider: Optional[str] = Field(default=None, description="Resolved provider identifier (e.g. 'openai', 'mock')")


class BaseAgentAdapter(ABC):
    """
    Abstract base class defining the adapter interface for executing prompts
    against AI agents or models.
    """

    @abstractmethod
    def execute(
        self,
        prompt: str,
        system_prompt: Optional[str] = None,
        model_name: Optional[str] = None,
        expected_output: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> AgentExecutionResult:
        """
        Executes a prompt against the target agent configuration and returns an AgentExecutionResult.
        """
        pass
